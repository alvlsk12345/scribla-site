<?php
declare(strict_types=1);
require __DIR__ . '/lib/http.php';

/* Приём журнала диагностики из приложения.
 *
 * Единственная ручка, с которой разговаривает не человек, а телефон.
 * Отсюда весь её вид: ни слова для показа на экране, ни языка страницы,
 * ни письма владельцу. Журналы читают тогда, когда что-то ищут, —
 * уведомлять о каждом незачем.
 *
 * Что приходит: служебные записи о работе приложения — что нажали,
 * где споткнулось. Ни звука, ни расшифровок, ни кусков текста: приложение
 * помечает такие записи у себя и в отправку их не кладёт (см. Contents
 * в Shared/Diagnostics.swift). Здесь мы этого проверить не можем и
 * не делаем вид, что можем, — вторая линия обороны стоит на телефоне,
 * а не тут.
 *
 * Чего здесь намеренно НЕТ — адреса отправителя. Все прочие ручки его
 * пишут: там за запросом стоит человек, оставивший почту, и адрес
 * помогает разобрать спам. Тут за запросом стоит телефон, который никто
 * не спрашивал, и IP превратил бы служебную запись в след перемещений.
 * Отличить один телефон от другого хватает случайной метки установки,
 * которую само приложение стирает, стоит выключить тумблер.
 */

/* Ключ отдельный, не админский.
 *
 * Ключ этой ручки лежит в приложении, а приложение раздаётся в App Store —
 * то есть достаётся из архива любым желающим. Считать его секретом нельзя;
 * его работа — отсечь случайных ботов, а не злоумышленника. Поэтому он
 * не может быть тем же, что у админки и выкладки: иначе вскрытый архив
 * отдавал бы и чужую почту, и право развернуть на сайте что угодно.
 *
 * Пустой файл или его отсутствие означают «ручки нет» — тем же способом,
 * что у админки. Так приём выключается одной строкой, без правки кода.
 */
$keyFile = data_dir() . '/log.key';
$key = is_file($keyFile) ? trim((string) file_get_contents($keyFile)) : '';
if ($key === '') { say(404, ['error' => 'Не найдено']); }

require_post();

/* Тело читаем сами, а не через body(): для подписи нужны те самые байты,
 * что подписывал телефон. Разбор в массив и обратно даёт другую строку —
 * порядок ключей, пробелы, экранирование юникода, — и подпись не сойдётся
 * никогда. */
$len = (int) ($_SERVER['CONTENT_LENGTH'] ?? 0);
if ($len > SCRIBLA_MAX_BODY) { say(413, ['error' => 'Слишком длинно']); }

$raw = (string) file_get_contents('php://input', false, null, 0, SCRIBLA_MAX_BODY + 1);
if (strlen($raw) > SCRIBLA_MAX_BODY) { say(413, ['error' => 'Слишком длинно']); }

$sign = (string) ($_SERVER['HTTP_X_SCRIBLA_SIGN'] ?? '');
if (!hash_equals(hash_hmac('sha256', $raw, $key), $sign)) {
    say(401, ['error' => 'Нет']);
}

$in = json_decode($raw ?: '[]', true);
if (!is_array($in)) { say(400, ['error' => 'Не разобрали запрос']); }

/* Метка установки — единственное, чем одна пачка отличается от другой.
 * Форму проверяем строго: она попадёт в имя ничего, но в файл попадёт,
 * а мусор в файле мешает потом искать. */
$install = (string) ($in['install'] ?? '');
if (!preg_match('/^[0-9A-Fa-f-]{8,40}$/', $install)) {
    say(400, ['error' => 'Не разобрали запрос']);
}

/* Частоту считаем по метке установки, а не по адресу.
 *
 * За одним адресом мобильного оператора сидят тысячи телефонов, и лимит
 * по IP отбивал бы честные пачки у случайных людей. Приложение шлёт
 * не чаще раза в полчаса — двадцать за десять минут это потолок,
 * до которого при исправной работе не добраться. */
if (too_often('log:' . $install, 20, 600)) {
    say(429, ['error' => 'Слишком часто']);
}

$entries = $in['entries'] ?? [];
if (!is_array($entries) || $entries === []) { say(400, ['error' => 'Пусто']); }
if (count($entries) > 500) { $entries = array_slice($entries, 0, 500); }

/* Об устройстве — только то, без чего запись бесполезна: версия сборки,
 * версия системы, модель. По ним отличают «сломано у всех на iOS 19»
 * от «сломано на одном телефоне». */
$about = [
    'app'    => cut((string) ($in['app'] ?? ''), 40),
    'os'     => cut((string) ($in['os'] ?? ''), 20),
    'device' => cut((string) ($in['device'] ?? ''), 40),
    'locale' => cut((string) ($in['locale'] ?? ''), 10),
];

/* Файл на день, а не на установку.
 *
 * Ротация тогда — одна строка в cron по имени файла, без обхода
 * содержимого. Искать по телефону это не мешает: метка установки стоит
 * в каждой строке, и `grep` находит всё про него разом. */
$dir = data_dir() . '/logs';
if (!is_dir($dir) && !@mkdir($dir, 0700, true) && !is_dir($dir)) {
    /* Каталог не завёлся — разбираться будет владелец по журналу сервера.
     * Телефону отвечаем честно: не приняли, пусть придёт ещё раз. Молча
     * сказать «принято» нельзя — он сотрёт у себя очередь. */
    error_log('scribla: не создать ' . $dir);
    say(503, ['error' => 'Не сейчас']);
}

$file = 'logs/' . gmdate('Y-m-d') . '.jsonl';
$stored = 0;

foreach ($entries as $entry) {
    if (!is_array($entry)) { continue; }

    $message = cut((string) ($entry['message'] ?? ''), 1000);
    if ($message === '') { continue; }

    store($file, [
        'install' => $install,
        'at'      => cut((string) ($entry['at'] ?? ''), 32),
        'got'     => gmdate('c'),
        'source'  => cut((string) ($entry['source'] ?? ''), 20),
        'message' => $message,
    ] + $about);
    $stored++;
}

say(200, ['stored' => $stored]);

/** Обрезка по символам с чисткой переводов строк.
 *
 * Перевод строки внутри значения разорвал бы строку JSONL надвое, и файл
 * перестал бы разбираться с той записи и до конца дня. Формат держится
 * на том, что запись — это ровно одна строка. */
function cut(string $s, int $limit): string
{
    $s = preg_replace('/[\r\n\t]+/u', ' ', $s) ?? '';
    return mb_substr(trim($s), 0, $limit, 'UTF-8');
}
