'use strict';

/* Фильтр брани для формы отзывов.
 *
 * Задача не «запретить», а «пометить»: письмо принимается в любом
 * случае, помеченное просто читают глазами. Отсюда две вещи, которые
 * обычно делают наоборот:
 *
 *  • список — корни, а не слова. Словоформ у русского мата тысячи,
 *    перечислять их бессмысленно: приставки и суффиксы бесконечны;
 *  • главная работа не в списке, а в нормализации. Кто прячется, пишет
 *    не словарным словом, а «с.у.к.а», «cyкa» латиницей или «сууука».
 *
 * ГЛАВНЫЙ УРОК, оплаченный провалом на стенде. Первая версия убирала
 * из текста вообще все разделители и склеивала строку в одно слово.
 * Она ловила спрятанное — и заодно метила «тебе баня» (стык даёт
 * «еба»), «всё бы ничего» («ебы»), «дам андроид» («манд»). Пять ложных
 * из шести обычных фраз. Пометка, которая срабатывает на каждой второй
 * фразе, бесполезна ровно так же, как не срабатывающая никогда.
 *
 * Поэтому склейка теперь не сплошная: слова остаются словами, а
 * склеиваются только цепочки одиночных букв — то есть ровно та запись,
 * ради которой приём и существует.
 */

/* Латиница и цифры, которыми подменяют кириллицу. Подобрано по
 * начертанию: важно не звучание, а то, что глаз читает как русскую. */
const LOOKALIKE = {
  a: 'а', b: 'в', c: 'с', e: 'е', h: 'н', k: 'к', m: 'м', o: 'о',
  p: 'р', t: 'т', x: 'х', y: 'у', u: 'и', n: 'п', r: 'г',
  3: 'е', 0: 'о', 4: 'ч', 6: 'б', 9: 'я', 1: 'и', 7: 'т',
  '@': 'а', '|': 'и',
};

/** Текст → список слов в нормальном виде: без ё, без латиницы,
 *  без растянутых букв. Границы слов сохраняются — в этом весь смысл. */
function words(input) {
  return String(input)
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[a-z0-9@|]/g, ch => LOOKALIKE[ch] || ch)
    .replace(/[^а-я]+/g, ' ')
    .trim()
    .split(/\s+/)
    .map(w => w.replace(/(.)\1+/g, '$1'))
    .filter(Boolean);
}

/** Цепочки одиночных букв склеиваем обратно: «с у к а» → «сука».
 *  Три и больше подряд — потому что «в и о» бывает в живой речи,
 *  а «с у к а» уже нет. */
function unspace(list) {
  const out = [];
  let run = [];
  const flush = () => { if (run.length >= 3) out.push(run.join('')); run = []; };
  for (const w of list) {
    if (w.length === 1) run.push(w);
    else { flush(); out.push(w); }
  }
  flush();
  return out;
}

/* Четыре семейства нельзя искать простым вхождением: их буквы слишком
 * часто попадаются в середине обычных слов. Проверено на стенде, а не
 * придумано, — вот что ловилось до этой правки:
 *
 *   «еб»    — тебе, себе, хлебе, требе
 *   «бля»   — рубля, оглобля   (на странице про переводы это смертельно)
 *   «манда» — команда, командир
 *   «ху»    — уху
 *
 * Общее у настоящих слов одно: корень стоит в начале, максимум после
 * приставки. У ложных — в середине. На этом и ловим. */
const ANCHORED = [
  /^(?:за|на|вы|при|у|до|пере|под|разъ|раз|съ|объ|по|от|из|про|недо)?еб/,
  /^(?:на|по|о|за)?ху[йеяию]/,
  /^бля/,
  /^манда/,
  /^(?:на|по)?хер/,
];

/* Корни в нормализованном виде: без ё, без сдвоенных букв.
 * Эти ищутся простым вхождением — в середине слова они не встречаются. */
const ROOTS = [
  'пизд', 'пезд',
  'бляд', 'блят',
  'муде', 'мудо', 'мудак', 'мудил',
  'гандон', 'гондон',
  'залуп', 'дроч', 'пидор', 'пидар', 'педик',
  'сука', 'суки', 'суке', 'суку', 'сучар', 'сучк',
  'срак', 'срать', 'обосра', 'просра',
  'говн', 'гавн', 'дерьм',
  'долбо', 'шлюх',
  'придур', 'дебил', 'кретин', 'тупиц', 'ублюд', 'мраз', 'падл', 'сволоч', 'урод',
];

/* Английская брань — по латинице, до подмены на кириллицу. */
const EN = [
  'fuck', 'shit', 'bitch', 'bastard', 'asshole', 'cunt',
  'motherfuck', 'wanker', 'twat', 'douche', 'retard',
  'faggot', 'whore', 'slut', 'dickhead', 'jackass',
];

/* Начала слов, которые совпадают с корнем по случайности. Список
 * короткий намеренно: он растёт по живым промахам, а не по догадкам. */
const ALLOW = [
  'мудр',                          // мудрый, мудрость
  'мандарин', 'мандат', 'мандол',  // начинаются на «манда»
  'херсон', 'хертфорд',            // начинаются на «хер»
  'хутор', 'хулиган',              // начинаются на «ху»
  'сукно', 'сукна', 'сукон',
  'дроздов', 'дрожж',              // «дроч»
  'ебип',                          // «Египет» после подмены латиницы
];

const allowed = w => ALLOW.some(a => w.startsWith(a));

function ruWords(text) {
  const list = words(text);
  // Оба варианта: слова как есть и склеенные цепочки одиночных букв.
  return [...new Set([...list, ...unspace(list)])];
}

function enWords(text) {
  return String(text).toLowerCase()
    .replace(/[^a-z]+/g, ' ')
    .trim().split(/\s+/)
    .map(w => w.replace(/(.)\1+/g, '$1'))
    .filter(Boolean);
}

/** Что именно совпало. Нужно, когда разбираешь промах и не хочешь гадать. */
function found(text) {
  if (!text) return [];
  const ru = ruWords(text), en = enWords(text);
  const hits = [];
  for (const re of ANCHORED)
    if (ru.some(w => !allowed(w) && re.test(w))) hits.push(String(re));
  for (const r of ROOTS)
    if (ru.some(w => !allowed(w) && w.includes(r))) hits.push(r);
  for (const w of EN)
    if (en.some(x => x.includes(w.replace(/(.)\1+/g, '$1')))) hits.push(w);
  return [...new Set(hits)];
}

/**
 * Есть ли в тексте брань.
 * @param {string} text
 * @returns {boolean}
 */
function isFoul(text) {
  return found(text).length > 0;
}

module.exports = { isFoul, found, words, unspace };
