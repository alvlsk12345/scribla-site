'use strict';

/* Проверки фильтра брани. Список случаев важнее самого фильтра:
 * он ловит не «плохие слова», а способы их спрятать. */

const { isFoul, found } = require('../lib/profanity');

const FOUL = [
  'какого хуя оно не работает',
  'это полная хуйня',
  'пиздец а не клавиатура',
  'заебало переписывать за ней',
  'блядь опять микрофон отвалился',
  // спрятанное
  'с.у.к.а какая программа',
  'с у к а какая программа',
  'сууууука',
  'ХУЙНЯ полная',
  'cyкa',                       // латиница вместо кириллицы
  'п1зд3ц',                     // цифры вместо букв
  'н-а-х-е-р это надо',
  'what the fuck is this',
  'this is shit',
  'FUUUCK',
];

const CLEAN = [
  'Не распознаёт имена, приходится править руками',
  'Микрофон перестал работать после звонка',
  'Хочу словарь замен побольше',
  'Спасибо, отличная штука',
  'Sometimes the keyboard does not see the text field',
  'Скатерть из сукна на столе',
  'Мудрость приходит с годами',
  'Купил мандарины на рынке',
  'Хулиган во дворе',
  'Отправил письмо в Херсон',
  'assessment of the accessibility',   // «ass» внутри слова
  'Классная штука, спасибо',
  // Стыки соседних слов. На них первая версия фильтра и погорела:
  // сплошная склейка давала «еба», «ебы», «манд» из ничего.
  'тебе баня после бассейна',
  'всё бы ничего, но микрофон',
  'себе бы такое на телефон',
  'в теме бывает и хуже',
  'дам андроид посмотреть',
  'не хватает ещё бы истории',
  'это не про хулиганов',
  'мудрое решение с полосой правки',
  'купил мандарины на рынке',
  'скатерть из сукна',
];

let bad = 0;

for (const s of FOUL) {
  if (!isFoul(s)) { console.log('ПРОПУСТИЛ:', JSON.stringify(s)); bad++; }
}
for (const s of CLEAN) {
  if (isFoul(s)) { console.log('ЛОЖНОЕ:   ', JSON.stringify(s), '→', found(s)); bad++; }
}

const total = FOUL.length + CLEAN.length;
if (bad) {
  console.log(`\n${bad} из ${total} мимо.`);
  process.exit(1);
}
console.log(`Все ${total} проверок сошлись.`);
